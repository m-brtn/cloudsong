#!/usr/bin/env python3
"""Prepare the approved Rodin export. Offline authoring tool; requires numpy and Pillow.

Keeps the original export intact, normalizes size, keeps the strongest four of all
16 skin influences, repairs the hood/cape/boot binding, and projects separate
energy marks onto the cape. Welded garment seams retain continuous skin weights. Outputs the source GLB for Quench's cooker and rig metadata.
"""
import io
import heapq
import json
import struct
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'art/character-v3/export/hero-rigged.glb'
b = source.read_bytes()
length = struct.unpack_from('<I', b, 12)[0]
d = json.loads(b[20:20+length])
data = b[28+length:]
DT = {5121: 'u1', 5126: '<f4', 5123: '<u2', 5125: '<u4'}
SZ = {'VEC3': 3, 'VEC4': 4, 'VEC2': 2, 'SCALAR': 1, 'MAT4': 16}
def read(i):
    a = d['accessors'][i]
    v = d['bufferViews'][a['bufferView']]
    return np.frombuffer(data, dtype=DT[a['componentType']], count=a['count']*SZ[a['type']],
                         offset=v.get('byteOffset', 0)+a.get('byteOffset', 0)).reshape(a['count'], -1).copy()

p, normals, uv = read(0), read(1), read(2)
indices = read(11).reshape(-1, 3)
joints = d['skins'][0]['joints']
names = [d['nodes'][i]['name'] for i in joints]
parents = [-1]*len(joints)
for i, node in enumerate(joints):
    for child in d['nodes'][node].get('children', []):
        if child in joints: parents[joints.index(child)] = i
bind = np.linalg.inv(read(12).reshape(-1, 4, 4).transpose(0, 2, 1))
scale = 1.12 / float(p[:, 1].max()-p[:, 1].min())
origin = np.array([0, p[:, 1].min(), 0])
p = (p-origin)*scale
bind[:, :3, 3] = (bind[:, :3, 3]-origin)*scale
# Tailor the crown above the face opening. The generated surface was a thick,
# rounded cone, so even bending its rig looked like tipping a solid helmet.
# Keep the aperture and head volume intact; the free crown narrows into two
# shallow cloth panels. The seam follows the tailored fold and bends with the hood chain.
def hood_shape(points):
    shaped = points.copy()
    t = np.clip((points[:,1]-.94)/.18, 0, 1)
    fade = t*t*(3-2*t)
    centre_z = .025 + .008*t
    x = points[:,0] - .009*fade
    z = points[:,2] - centre_z
    angle = np.arctan2(z, x)
    fold = .004 * np.sin(np.pi*t)**2 * np.cos(2*angle)
    radius = np.maximum(np.sqrt(x*x+z*z), .001)
    # Tailor a narrow folded crown into the rest mesh. Motion must never have
    # to crush an inflated cone to produce the silhouette of soft fabric.
    shaped[:,0] = x * (1-.36*fade + fold/radius) + .022*fade*t
    shaped[:,2] = centre_z + z * (1-.60*fade + fold/radius) - .062*fade*t
    shaped[:,1] -= .035*fade*t
    return shaped

hood_source = p.copy()
p = hood_shape(hood_source)
# Transform supplied normals with the deformation's Jacobian. Rebuilding all
# normals would erase the authored aperture edge and seams elsewhere on the mesh.
hood = hood_source[:,1] > .94
if np.any(hood):
    source_points = hood_source[hood]
    jacobian = np.empty((len(source_points),3,3))
    for axis in range(3):
        step = np.zeros(3); step[axis] = 1e-5
        jacobian[:,:,axis] = (hood_shape(source_points+step)-hood_shape(source_points-step))/(2e-5)
    adjusted = np.linalg.solve(jacobian.transpose(0,2,1), normals[hood,:,None])[:,:,0]
    normals[hood] = adjusted/np.linalg.norm(adjusted,axis=1)[:,None]
# Give nearly straight autogenerated knees a stable human bending plane. Their
# sub-millimetre sideways rest bend is not a usable anatomical hinge axis.
for side in ('Left', 'Right'):
    hip, knee, ankle = [names.index(side+n) for n in ('UpLeg','Leg','Foot')]
    a, b, c = bind[[hip,knee,ankle], :3, 3].copy()
    t = np.linalg.norm(b-a)/(np.linalg.norm(b-a)+np.linalg.norm(c-b))
    bind[knee,:3,3] = a+(c-a)*t+np.array([0,0,.018])
    toe = names.index(side+'ToeBase')
    bind[toe,:3,3] = [bind[ankle,0,3], .025, .045]
# Scale is baked into vertices and translations, leaving all joint frames orthonormal.
weights = np.zeros((len(p), len(joints)), dtype=np.float64)
for group in range(4):
    js, ws = read(3+group), read(7+group)
    for col in range(4): np.add.at(weights, (np.arange(len(p)), js[:, col]), ws[:, col])
# The service put Hood1..3 down inside the torso. Remove those weights, then bind
# just the crown to an upright chain. The face and lower hood remain on Head.
head = names.index('Head')
for name in ('Hood1', 'Hood2', 'Hood3'):
    j = names.index(name)
    weights[:, head] += weights[:, j]
    weights[:, j] = 0
for k, name in enumerate(('Hood1', 'Hood2', 'Hood3')):
    j = names.index(name)
    bind[j] = np.eye(4)
    bind[j, :3, 3] = hood_shape(np.array([[0., .925 + k*.075, .025 + k*.004]]))[0]
for i in np.where(p[:, 1] > .925)[0]:
    t = np.clip((hood_source[i, 1]-.925)/.075, 0, 2)
    lo = min(int(t), 1)
    f = t-lo
    weights[i] = 0
    weights[i, names.index('Hood'+str(lo+1))] = 1-f
    weights[i, names.index('Hood'+str(lo+2))] = f
    # Fade from the rigid rim into the crown; a hard height threshold tears the
    # silhouette when the spring bends vertices on opposite sides of a seam.
    # The front rim frames the face and must not shear when the free tip bends.
    # The rear cloth starts yielding lower, giving it a soft fold over the skull.
    front = np.clip((p[i,2]-.045)/.065, 0, 1)
    start = .925 + .035*front
    blend = np.clip((p[i, 1]-start)/.065, 0, 1)
    blend = blend*blend*(3-2*blend)
    weights[i] *= blend
    weights[i, head] = 1-blend
# The inner tunic must follow the torso, not the nearby wrists/forearms.
# Restrict this correction to the central garment below the armpits; leave the
# sleeves and hands untouched. This prevents a swing pulling a flap through an arm.
for i in np.where((abs(p[:, 0]) < .073) & (p[:, 1] > .43) & (p[:, 1] < .66))[0]:
    for j, name in enumerate(names):
        if 'Arm' in name or 'Hand' in name:
            weights[i, names.index('Spine')] += weights[i, j]
            weights[i, j] = 0

def top4(w):
    js = np.argsort(-w, axis=1, kind='stable')[:, :4]
    ws = np.take_along_axis(w, js, axis=1)
    ws /= ws.sum(axis=1, keepdims=True)
    return js.astype('<u2'), ws.astype('<f4')

# Find the actual red cape surface for mark projection and trail attachment.
v = d['bufferViews'][d['images'][1]['bufferView']]
im = np.array(Image.open(io.BytesIO(data[v['byteOffset']:v['byteOffset']+v['byteLength']])).convert('RGB'))
h, w = im.shape[:2]
c = im[np.clip((uv[:, 1]*h).astype(int), 0, h-1), np.clip((uv[:, 0]*w).astype(int), 0, w-1)].astype(float)/255
cape = (c[:, 0] > c[:, 1]*1.4) & (c[:, 0] > c[:, 2]*1.5) & (c[:, 0] > .3)
# Rigging assigned cape vertices to Hood, arms and thighs. Rebind the garment
# to a symmetric set of four cloth chains, preserving the authored geometry.
# Include its gold trim and adjacent edge vertices, but exclude head and boots.
gold = (c[:,0] > .35) & (c[:,0] > c[:,1]*1.2) & (c[:,1] > c[:,2]*1.8)
garment = (cape | gold) & (p[:,1] > .24) & (p[:,1] < .78)
# UV seams duplicate vertices. Give coincident vertices the same classification
# and weights so that animation cannot open cracks along those seams.
_, weld = np.unique(np.round(p, 6), axis=0, return_inverse=True)
votes = np.bincount(weld, weights=garment.astype(float))
counts = np.bincount(weld)
garment = (votes[weld]/counts[weld] > .5)
# Remove stray garment/hood influences from the inner tunic and limbs as well.
# Otherwise moving a cloth chain drags holes out of the white undergarment.
cloth = [j for j,n in enumerate(names) if 'Cape' in n or 'Hood' in n]
body = [names.index(n) for n in ['Hips','Spine','Chest','Neck','Head','LeftArm','LeftForeArm','LeftHand',
                                'RightArm','RightForeArm','RightHand','LeftUpLeg','LeftLeg','LeftFoot',
                                'RightUpLeg','RightLeg','RightFoot']]
def smooth(a, b, value):
    f = float(np.clip((value-a)/(b-a),0,1))
    return f*f*(3-2*f)

for i in range(len(p)):
    if p[i,1] > .925: continue  # the repaired hood crown
    weights[i,cloth] = 0
    if p[i,1] < .72: weights[i,head] = 0
    if p[i,1] > .78:
        weights[i] = 0; weights[i,head] = 1
    elif p[i,1] < .17:
        # Keep the tall shaft rigid with the shin; the heel and sole articulate
        # at the ankle, and only the front of the sole flexes at the ball.
        # A narrow ankle blend avoids bending the entire boot like a rubber hose.
        side = 'Left' if p[i,0] > 0 else 'Right'
        toe = float(np.clip((p[i,2]-.025)/.045,0,1))
        toe = toe*toe*(3-2*toe)
        toe *= float(1-np.clip((p[i,1]-.045)/.025,0,1))
        ankle = float(np.clip((.100-p[i,1])/.035,0,1))
        ankle = ankle*ankle*(3-2*ankle)
        weights[i] = 0
        weights[i,names.index(side+'ToeBase')] = toe
        weights[i,names.index(side+'Foot')] = (1-toe)*ankle
        weights[i,names.index(side+'Leg')] = (1-toe)*(1-ankle)
    if weights[i].sum() < 1e-6:
        nearest = min(body,key=lambda j: np.linalg.norm(p[i]-bind[j,:3,3]))
        weights[i,nearest] = 1
    weights[i] /= weights[i].sum()
body_weights = weights.copy()
for side, sign in [('Left',1), ('Right',-1)]:
    for region in ('Edge','Rear'):
        for level in range(3):
            j = names.index(side+'Cape'+region+str(level+1))
            bind[j] = np.eye(4)
            bind[j,:3,3] = ([sign*(.11+.055*level), .715-.20*level, -.015*level]
                            if region == 'Edge' else [sign*(.055+.025*level), .715-.20*level, -.055-.05*level])
cape_chains = [[names.index(side+'Cape'+region+str(level)) for level in (1,2,3)]
               for side,region in [('Left','Edge'),('Left','Rear'),('Right','Rear'),('Right','Edge')]]
for i in range(len(p)):
    x,y,z = p[i]
    weights[i] = 0
    chest = float(np.clip((y-.70)/.065,0,1))
    # Triangulate the cage in garment coordinates. Each cloth point uses three
    # adjacent cage joints, continuously across each diagonal. The old bilinear
    # blend could use eight joints and jumped when top4 dropped a different one.
    angle = np.arctan2(x, -z+.025)
    across = float(np.interp(angle,[-2.1,-.45,.45,2.1],[3,2,1,0]))
    col = min(int(across),2); u = across-col
    t = float(np.clip((.715-y)/.20,0,2))
    row = min(int(t),1); v = t-row
    if u+v <= 1:
        weights[i,cape_chains[col][row]] = 1-u-v
        weights[i,cape_chains[col+1][row]] = u
        weights[i,cape_chains[col][row+1]] = v
    else:
        weights[i,cape_chains[col+1][row+1]] = u+v-1
        weights[i,cape_chains[col+1][row]] = 1-v
        weights[i,cape_chains[col][row+1]] = 1-u
    weights[i] *= 1-chest
    weights[i,names.index('Chest')] += chest
    # The red garment also has two overlapping front panels over the tunic.
    # They are sewn to the chest, not part of the flying rear wing. Letting the
    # edge chains carry them turned their folded gold trim into loops in flight.
    # Smooth spatial bands retain a little flutter while leaving the outer wing
    # and back entirely free; coincident seam vertices get identical factors.
    front = smooth(.015,.075,z) * smooth(.30,.40,y)
    sewn = .94*front
    weights[i] *= 1-sewn
    torso = smooth(.48,.67,y)
    weights[i,names.index('Chest')] += sewn*torso
    weights[i,names.index('Spine')] += sewn*(1-torso)
# Keep welded seams continuous, but do not spread cape binding into the white
# tunic and sleeves. Broad colour-blind diffusion stretched them into membranes
# between the torso and the open cape during a flap. Their existing body skin
# retains the arm joints on sleeves and the torso joints on the inner tunic.
neutral = (c.min(axis=1) > .28) & (c.max(axis=1) < c.min(axis=1)*1.6)
inner_tunic = (abs(p[:,0]) < .18) & (p[:,1] > .33) & (p[:,1] < .70) & (p[:,2] > -.04)
sleeves = (abs(p[:,0]) > .085) & (p[:,1] > .48) & (p[:,1] < .73)
body_fabric = neutral & (inner_tunic | sleeves)
body_votes = np.bincount(weld, weights=body_fabric.astype(float))
body_seam = body_votes/counts > .5
faces = weld[indices]
# The export's triangles cross painted material boundaries. A white triangle
# can have a corner whose UV samples red trim; testing only vertex colours
# leaves that one corner on Cape and stretches the otherwise rigid white face.
# Classify the triangle interior as well, then sew every corner of each body
# face to the same body binding. Adjacent red faces share those sewn vertices;
# no triangles are removed and no duplicated, disconnected boundary is made.
face_uv = uv[indices].mean(axis=1)
texture_height, texture_width = im.shape[:2]
face_color = im[np.clip((face_uv[:,1]*texture_height).astype(int),0,texture_height-1),
                np.clip((face_uv[:,0]*texture_width).astype(int),0,texture_width-1)].astype(float)/255
face_position = p[indices].mean(axis=1)
face_neutral = ((face_color.min(axis=1) > .28) &
                (face_color.max(axis=1) < face_color.min(axis=1)*1.6))
face_body = ((abs(face_position[:,0]) < .18) & (face_position[:,1] > .33) &
             (face_position[:,1] < .70) & (face_position[:,2] > -.04))
face_sleeve = ((abs(face_position[:,0]) > .085) & (face_position[:,1] > .48) &
               (face_position[:,1] < .73) & (face_position[:,2] > -.04))
body_faces = face_neutral & (face_body | face_sleeve) & (neutral[indices].sum(axis=1) >= 1)
body_seam[np.unique(faces[body_faces])] = True
# The auto-rig also attached the outer tunic to the thighs, including cloth
# above the hip joint. A flap then pulled the inner tunic in two directions.
# Preserve actual limb skin inside the thigh capsules and the sleeve's arm
# weights, but hang the outer tunic shell from Hips/Spine.
leg_joints = [j for j,n in enumerate(names) if 'Leg' in n or 'Foot' in n or 'Toe' in n]
arm_joints = [j for j,n in enumerate(names) if 'Arm' in n or 'Hand' in n]
for i in np.where(body_seam[weld])[0]:
    x,y,z = p[i]
    if y < .33 or y > .73: continue
    torso_weights = np.zeros(len(names))
    spine = smooth(.43,.61,y)
    torso_weights[names.index('Hips')] = 1-spine
    torso_weights[names.index('Spine')] = spine
    if y > .50:
        body_weights[i,leg_joints] = 0
        total = body_weights[i].sum()
        body_weights[i] = body_weights[i]/total if total > 1e-6 else torso_weights
    if y < .60 and abs(x) < .17:
        distance = float('inf')
        for side in ('Left','Right'):
            a = bind[names.index(side+'UpLeg'),:3,3]
            b = bind[names.index(side+'Leg'),:3,3]
            t = np.clip(np.dot(p[i]-a,b-a)/np.dot(b-a,b-a),0,1)
            distance = min(distance, np.linalg.norm(p[i]-(a+t*(b-a))))
        shell = max(smooth(.43,.48,y),smooth(.042,.06,distance))
        shell *= smooth(.33,.365,y)*(1-smooth(.2,.6,body_weights[i,arm_joints].sum()))
        body_weights[i] = body_weights[i]*(1-shell)+torso_weights*shell
# When the lower cape is sewn to the tunic, its attachment follows the torso as
# well. The autogenerated body fallback on red vertices was often a thigh.
for i in np.where(garment & (p[:,1] < .60))[0]:
    spine = smooth(.43,.61,p[i,1])
    body_weights[i] = 0
    body_weights[i,names.index('Hips')] = 1-spine
    body_weights[i,names.index('Spine')] = spine
edges = np.concatenate([faces[:,[0,1]], faces[:,[1,2]], faces[:,[2,0]]])
edges = np.unique(np.sort(edges,axis=1),axis=0)
a, b = edges.T
mix = votes/counts
# Smooth within a garment only. UV duplicates are averaged below regardless of
# their colour, so the boundary remains sewn without driving both fabrics alike.
same_fabric = ((mix[a] > .5) == (mix[b] > .5)) & (body_seam[a] == body_seam[b])
a, b = a[same_fabric], b[same_fabric]
mix[body_seam] = 0
for _ in range(5):
    total = mix.copy(); degree = np.ones(len(counts))
    np.add.at(total,a,mix[b]); np.add.at(total,b,mix[a])
    np.add.at(degree,a,1); np.add.at(degree,b,1)
    mix = total/degree
# A sewn edge is an attachment region, not a binary material switch. The source
# welds the front panels to the tunic: switching from body to free cloth across a
# 1 mm triangle stretched its gold hem by 73x in the recorded flap. Fade mobility
# over 12 cm measured ALONG the garment, keeping the rear sheet fully free.
_, first_weld = np.unique(weld,return_index=True)
weld_position = p[first_weld]
neighbours = [[] for _ in counts]
for a,b in edges:
    length = float(np.linalg.norm(weld_position[a]-weld_position[b]))
    neighbours[a].append((b,length)); neighbours[b].append((a,length))
distance = np.full(len(counts),np.inf)
queue = []
for i in np.where(body_seam)[0]:
    distance[i] = 0
    heapq.heappush(queue,(0,i))
while queue:
    current,i = heapq.heappop(queue)
    if current != distance[i]: continue
    for other,length in neighbours[i]:
        candidate = current+length
        if candidate < distance[other]:
            distance[other] = candidate
            heapq.heappush(queue,(candidate,other))
mobility = np.clip(distance/.12,0,1)
mix *= mobility*mobility*(3-2*mobility)
weights = body_weights*(1-mix[weld,None]) + weights*mix[weld,None]
combined = np.zeros((len(counts),len(names)))
np.add.at(combined,weld,weights)
weights = combined[weld]/counts[weld,None]
cape = garment
js, ws = top4(weights)
tri = indices[np.all(cape[indices], axis=1)]
# Project from the back along +z. Barycentric weights make attachments deform
# exactly like the visible triangles, including their original skin blending.
def project(x, y):
    a, b, c = p[tri[:, 0]], p[tri[:, 1]], p[tri[:, 2]]
    v0, v1, v2 = b-a, c-a, np.array([x, y, 0])-a
    det = v0[:, 0]*v1[:, 1]-v0[:, 1]*v1[:, 0]
    safe = np.where(abs(det) > 1e-10, det, 1)
    u = (v2[:, 0]*v1[:, 1]-v2[:, 1]*v1[:, 0])/safe
    v = (v0[:, 0]*v2[:, 1]-v0[:, 1]*v2[:, 0])/safe
    valid = (abs(det) > 1e-10) & (u >= -1e-5) & (v >= -1e-5) & (u+v <= 1.00001)
    z = a[:, 2]+u*v0[:, 2]+v*v1[:, 2]
    z[~valid] = 100
    t = int(np.argmin(z))
    if z[t] == 100: raise ValueError(('No cape at mark', x, y))
    bary = np.array([1-u[t]-v[t], u[t], v[t]])
    pos = bary @ p[tri[t]]
    normal = bary @ normals[tri[t]]
    normal /= np.linalg.norm(normal)
    if normal[2] > 0: normal = -normal
    weight = bary @ weights[tri[t]]
    return pos+normal*.002, normal, weight
mark_uv = [(.5,.2),(.5,.37),(.5,.54),(.5,.71),(.36,.3),(.64,.3),(.34,.52),(.66,.52)]
mark_p, mark_n, mark_w, mark_tex, mark_ix, anchors = [], [], [], [], [], []
for k, (u, v) in enumerate(mark_uv):
    x, y = (u-.5)*.54, .685-v*.37
    anchor = project(x, y)
    anchors.append(anchor)
    # A small tessellated diamond, conforming to folds without a floating badge.
    pts = [(0,0), (0,.024), (.016,0), (0,-.024), (-.016,0)]
    base = len(mark_p)
    for dx, dy in pts:
        pp, nn, ww = project(x+dx, y+dy)
        mark_p.append(pp); mark_n.append(nn); mark_w.append(ww); mark_tex.append([k,0])
    for t in range(4): mark_ix.extend([base, base+1+t, base+1+(t+1)%4])
# Trail points are at the actual cape hem, not the old procedural cage.
for side in (1, -1):
    candidates = np.where(cape & (p[:, 1] < .47) & (p[:, 1] > .24) & (p[:, 0]*side > .1))[0]
    i = candidates[np.argmax(p[candidates, 0]*side)]
    anchors.append((p[i], normals[i], weights[i]))
anchors.append(project(0, .435))

# Rebuild a compact source GLB with four influences and the separate mark mesh.
out = bytearray(); views = []; accessors = []
def raw(blob):
    while len(out)%4: out.append(0)
    index = len(views); views.append({'buffer':0, 'byteOffset':len(out), 'byteLength':len(blob)})
    out.extend(blob); return index
def array(a, typ, ct=5126):
    a = np.asarray(a, dtype=DT[ct]); view = raw(a.tobytes())
    obj = {'bufferView':view, 'componentType':ct, 'count':len(a), 'type':typ}
    if typ == 'VEC3': obj.update(min=a.min(axis=0).tolist(), max=a.max(axis=0).tolist())
    idx = len(accessors); accessors.append(obj); return idx
attrs = {'POSITION':array(p,'VEC3'), 'NORMAL':array(normals,'VEC3'), 'TEXCOORD_0':array(uv,'VEC2'),
         'JOINTS_0':array(js,'VEC4',5123), 'WEIGHTS_0':array(ws,'VEC4')}
ix = array(indices.reshape(-1), 'SCALAR', 5125)
mj, mw = top4(np.array(mark_w))
ma = {'POSITION':array(mark_p,'VEC3'), 'NORMAL':array(mark_n,'VEC3'), 'TEXCOORD_0':array(mark_tex,'VEC2'),
      'JOINTS_0':array(mj,'VEC4',5123), 'WEIGHTS_0':array(mw,'VEC4')}
mi = array(mark_ix, 'SCALAR',5125)
ib = array(np.linalg.inv(bind).transpose(0,2,1).reshape(-1,16), 'MAT4')
images = []
for image in d['images']:
    v = d['bufferViews'][image['bufferView']]
    images.append({'bufferView':raw(data[v['byteOffset']:v['byteOffset']+v['byteLength']]), 'mimeType':'image/png'})
nodes = []
for i, name in enumerate(names):
    local = np.linalg.inv(bind[parents[i]]) @ bind[i] if parents[i] >= 0 else bind[i]
    node = {'name':name, 'matrix':local.T.flatten().tolist()}
    children = [j for j, parent in enumerate(parents) if parent == i]
    if children: node['children'] = children
    nodes.append(node)
nodes.append({'name':'Cloudsong hero', 'mesh':0, 'skin':0})
material = d['materials'][0]
